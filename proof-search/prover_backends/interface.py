from typing import Any, Protocol

from .types import CompletionStatus, GoalState


class ProverInterface(Protocol):
    """Native clients must expose normalized state and session-owned checkpoints."""

    source_path: str
    file_path: str

    def is_loaded(self) -> bool: ...
    def load(self) -> bool: ...
    def restart(self) -> bool:
        """Preserve accepted work and checkpoints for the next load."""
        ...
    def close(self) -> None:
        """Remove the working copy; preserve the source file."""
        ...
    def has_active_proof(self) -> bool: ...
    def get_step_count(self) -> int:
        """Count accepted commands, excluding proof-opening commands."""
        ...
    def checkpoint(self) -> Any: ...
    def matches_checkpoint(self, checkpoint: Any) -> bool: ...
    def restore(self, checkpoint: Any) -> None:
        """Restore an ancestor or raise; reject foreign and abandoned checkpoints."""
        ...
    def extract_and_reset_tactics(self) -> list[str]: ...
    def get_goal_state(self) -> GoalState:
        """Include deferred and abandoned obligations; raise if state is unavailable."""
        ...
    def get_goal_str(self) -> str: ...
    def get_hypothesis(self) -> str: ...
    def execute(self, command: str) -> bool:
        """On rejection restore prior state; raise if restoration fails."""
        ...
    def execute_query(self, query: str) -> str | None:
        """Preserve proof state; return None on failure and set get_last_error()."""
        ...
    def get_last_error(self) -> str: ...
    def completion_status(self) -> CompletionStatus: ...
    def finalize(self) -> bool:
        """Validate all obligations and constraints; restore on rejection."""
        ...
    def get_proof_file_content(self) -> str: ...
    def extract_proof_context(self, content: str) -> str:
        """Extract the active proof and its dependencies using parsed context."""
        ...
