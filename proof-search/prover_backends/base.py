from typing import Any, Protocol

from .types import CompletionStatus, Goal, SearchResult, TacticEffect


class ProverBackend(Protocol):
    """Prover policies and operations used by the proof-search agent."""

    source_path: str
    file_path: str
    system_prompt: str
    tactic_instruction: str
    prompt_guidelines: str
    tactic_tool: dict
    query_tool: dict
    default_tactic: str
    automation_tactic: str | None
    interactive_prompt: str
    history_filename: str
    query_help: str
    proof_start_label: str

    def load(self) -> bool: ...
    def restart(self) -> bool:
        """Restart so that load can recover accepted work and its checkpoints."""
        ...
    def close(self) -> None:
        """Remove the working copy at file_path; preserve the source file."""
        ...
    def has_active_proof(self) -> bool: ...
    def get_step_count(self) -> int:
        """Count accepted tactics, excluding proof-opening commands."""
        ...
    def checkpoint(self) -> Any:
        """Return an opaque checkpoint belonging to this session."""
        ...
    def restore(self, checkpoint: Any) -> None:
        """Restore the current checkpoint or an ancestor; raise on failure.

        Reject foreign or abandoned checkpoints without changing proof state.
        """
        ...
    def matches_checkpoint(self, checkpoint: Any) -> bool: ...
    def extract_and_reset_tactics(self) -> list[str]: ...
    def get_goals(self) -> list[Goal]:
        """Return all current proof goals in order; raise if unavailable."""
        ...
    def get_goal_str(self) -> str: ...
    def get_hypothesis(self) -> str: ...
    def display_state(self) -> str: ...
    def apply_tactic(self, tactic: str) -> bool: ...
    def normalize_tactic(self, tactic: str) -> str: ...
    def tactic_effect(self, tactic: str) -> TacticEffect: ...
    def classify_command(self, command: str) -> str: ...
    def get_last_error(self) -> str: ...
    def include_in_history_feedback(self, tactic: str) -> bool: ...
    def error_hint(self, tactic: str, error: str) -> str: ...
    def completion_status(self) -> CompletionStatus: ...
    def finalize(self) -> bool:
        """Validate all obligations and constraints; reject unfinished or admitted proofs."""
        ...
    def get_proof_file_content(self) -> str: ...
    def extract_proof_context(self, content: str) -> str: ...
    def search(self, query: str, goal_context: str = "") -> SearchResult:
        """Set metadata['error'] on failure; no matches is a successful query."""
        ...
    def search_by_type(self, query_type: str, identifier: str | None = None,
                       pattern: str | None = None, goal_context: str = "") -> SearchResult:
        """Support search, print, print_assumptions, locate, about, and check.

        Failures, including unsupported operations, set metadata['error'].
        """
        ...
    def extract_goal_pattern(self, text: str) -> str: ...
    def count_goals(self, text: str) -> int: ...
